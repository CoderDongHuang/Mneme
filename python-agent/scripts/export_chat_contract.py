"""Export the citation schema and browser types from the Pydantic wire model.

Run with --check in CI; intentional contract changes must regenerate artifacts.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python-agent"))
from app.models.chat import Source  # noqa: E402


def typescript(schema: dict) -> str:
    if "anyOf" in schema:
        return " | ".join(typescript(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object":
        return f"Record<string, {typescript(schema['additionalProperties'])}>"
    return {"string": "string", "number": "number", "integer": "number", "null": "null"}[kind]


def artifacts() -> dict[Path, str]:
    # Serialization mode includes defaulted response fields, which are always
    # emitted on the wire even though callers need not supply them to Python.
    schema = Source.model_json_schema(mode="serialization")
    lines = ["// Generated by python-agent/scripts/export_chat_contract.py; do not edit.", "export interface ChatSource {"]
    for name, field in schema["properties"].items():
        lines.append(f"  {name}: {typescript(field)}")
    lines.extend(["}", ""])
    return {
        ROOT / "contracts/chat-source.schema.json": json.dumps(schema, ensure_ascii=False, indent=2) + "\n",
        ROOT / "contracts/chat-source.examples.json": json.dumps([
            Source(document_name="plain.txt", chunk_content="").model_dump(mode="json"),
            Source(document_name="report.pdf", chunk_content="图表证据", document_id="42", page=2,
                   visual_page=3, visual_region=[0.1, 0.2, 0.9, 0.8], ocr_confidence=0.88,
                   evidence_type="visual", chunk_type="table", score=0.91, section="Results",
                   retrieval_ranks={"dense:0": 2, "bm25": 1}, content_sha256="version-42",
                   indexed_at="2026-11-01T00:00:00Z", parser_version="v2").model_dump(mode="json"),
        ], ensure_ascii=False, indent=2) + "\n",
        ROOT / "frontend/src/api/generated/chat-source.d.ts": "\n".join(lines),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, expected in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    if stale:
        parser.exit(1, "Citation contract drift; regenerate with this script: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
