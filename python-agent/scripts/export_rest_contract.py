"""Generate public Gateway result types from the shared schema; --check rejects drift."""
import argparse
import json
from pathlib import Path

from export_stream_contract import check_vocabulary, ts_type

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name in ("gateway-result", "chat-session"):
        schema = json.loads((ROOT / f"contracts/{name}.schema.json").read_text(encoding="utf-8"))
        definitions = schema.get("$defs", {schema.get("title"): schema})
        lines = ["// Generated by python-agent/scripts/export_rest_contract.py; do not edit."]
        for title, definition in definitions.items():
            check_vocabulary(definition)
            lines.append(f"export type {title} = {ts_type(definition)}")
        expected = "\n".join(lines) + "\n"
        path = ROOT / f"frontend/src/api/generated/{name}.d.ts"
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                parser.exit(1, f"Gateway REST contract drift in {name}; run python python-agent/scripts/export_rest_contract.py\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
