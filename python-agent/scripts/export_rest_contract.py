"""Generate public Gateway result types from the shared schema; --check rejects drift."""
import argparse
import json
from pathlib import Path

from export_stream_contract import check_vocabulary, ts_type

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schema = json.loads((ROOT / "contracts/gateway-result.schema.json").read_text(encoding="utf-8"))
    check_vocabulary(schema)
    expected = ("// Generated by python-agent/scripts/export_rest_contract.py; do not edit.\n"
                f"export type GatewayResult = {ts_type(schema)}\n")
    path = ROOT / "frontend/src/api/generated/gateway-result.d.ts"
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Gateway REST contract drift; run python python-agent/scripts/export_rest_contract.py\n")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
