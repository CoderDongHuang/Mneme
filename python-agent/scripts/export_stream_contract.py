"""Generate SSE schemas and TypeScript types. CI uses --check to reject drift."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python-agent"))
from app.models.chat_stream import AGENT_EVENTS, AGENT_ONLY_EVENTS, EVENT_MODELS, TERMINAL_EVENTS  # noqa: E402

VOCABULARY = {"$ref", "title", "description", "default", "type", "properties", "required",
              "additionalProperties", "items", "anyOf", "const", "enum", "minimum", "maximum",
              "minLength", "maxLength", "maxItems"}


def check_vocabulary(schema):
    """Do not publish constraints the bounded Gateway/browser validators ignore."""
    if not isinstance(schema, dict):
        return
    unknown = schema.keys() - VOCABULARY
    if unknown:
        raise ValueError("Unsupported stream schema vocabulary: " + ", ".join(sorted(unknown)))
    for child in schema.get("properties", {}).values():
        check_vocabulary(child)
    for key in ("items", "additionalProperties"):
        check_vocabulary(schema.get(key))
    for child in schema.get("anyOf", []):
        check_vocabulary(child)


def ts_type(schema):
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema and schema.get("type") == "object":
        base = {key: value for key, value in schema.items() if key != "anyOf"}
        return ts_type(base) + " & (" + " | ".join(ts_type({"type": "object", **choice}) for choice in schema["anyOf"]) + ")"
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        if "properties" not in schema:
            return f"Record<string, {ts_type(schema['additionalProperties'])}>"
        required = schema.get("required", [])
        return "{ " + "; ".join(f"{key}{'' if key in required else '?'}: {ts_type(value)}"
                                 for key, value in schema["properties"].items()) + " }"
    return {"string": "string", "boolean": "boolean", "integer": "number", "number": "number", "null": "null"}[kind]


def artifacts():
    definitions, events = {}, {}
    for name, model in EVENT_MODELS.items():
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        events[name] = schema
    for schema in [*definitions.values(), *events.values()]:
        check_vocabulary(schema)
    contract = {"version": 1, "$defs": definitions, "events": events,
                "agent_events": list(AGENT_EVENTS), "agent_only_events": list(AGENT_ONLY_EVENTS), "terminal_events": list(TERMINAL_EVENTS)}
    wire = json.dumps(contract, ensure_ascii=False, indent=2) + "\n"
    types = ["// Generated by python-agent/scripts/export_stream_contract.py; do not edit."]
    types.extend(f"export type {key} = {ts_type(value)}" for key, value in definitions.items())
    types.append("export interface ChatStreamPayloads {")
    types.extend(f"  {key}: {ts_type(value)}" for key, value in events.items())
    types.extend(["}", "export type ChatStreamEvent = { [K in keyof ChatStreamPayloads]: { event: K; data: ChatStreamPayloads[K] } }[keyof ChatStreamPayloads]", ""])
    return {
        ROOT / "contracts/chat-stream.schema.json": wire,
        ROOT / "java-gateway/src/main/resources/contracts/chat-stream.schema.json": wire,
        ROOT / "frontend/src/api/generated/chat-stream.d.ts": "\n".join(types),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, expected in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    if stale:
        parser.exit(1, "Chat SSE contract drift; regenerate: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
